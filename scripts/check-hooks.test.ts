import { afterAll, expect, test } from "bun:test";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

const directory = await mkdtemp(join(tmpdir(), "mcp-cli-hooks-"));
const run = async (script: string, path: string) => {
  const child = Bun.spawn(["bun", script, path], { stdout: "pipe", stderr: "pipe" });
  const [exitCode, stderr] = await Promise.all([child.exited, new Response(child.stderr).text()]);
  return { exitCode, stderr };
};
afterAll(async () => rm(directory, { recursive: true, force: true }));

test("requires scope and rejects malformed conventional commit subjects", async () => {
  const file = join(directory, "COMMIT_EDITMSG");
  for (const message of ["feat: missing scope", "feat(): empty scope", "random message"]) {
    await writeFile(file, message);
    expect((await run("scripts/check-commit-message.ts", file)).exitCode).toBe(1);
  }
  await writeFile(file, "feat(cli)!: change command\n\nBody");
  expect((await run("scripts/check-commit-message.ts", file)).exitCode).toBe(0);
});

test("accepts git-authored subjects and skips comments and blank lines", async () => {
  const file = join(directory, "COMMIT_EDITMSG");
  const accepted = [
    "Merge branch 'main' into feature",
    'Revert "feat(cli): change command"',
    "fixup! feat(cli): change command",
    "squash! feat(cli): change command",
    "# Please enter the commit message\n\nfix(core): handle input\n# trailer",
    "\n\n  feat(mcp): add timeout\n",
  ];
  for (const message of accepted) {
    await writeFile(file, message);
    expect((await run("scripts/check-commit-message.ts", file)).exitCode, message).toBe(0);
  }
  for (const message of [
    "# only a comment\n",
    "Revert feat",
    "fixup!feat(cli): x",
    "\n# c\nrandom",
  ]) {
    await writeFile(file, message);
    expect((await run("scripts/check-commit-message.ts", file)).exitCode, message).toBe(1);
  }
});

test("rejects unsafe syntax and accepts arrows and method signatures", async () => {
  const file = join(directory, "sample.ts");
  await writeFile(file, "function bad(value: any) { return value! as unknown; }");
  const result = await run("scripts/check-code-rules.ts", file);
  expect(result.exitCode).toBe(1);
  expect(result.stderr.split("\n").filter(Boolean)).toHaveLength(4);
  await writeFile(file, "interface Port { run(): void }; const run = () => 1;");
  expect((await run("scripts/check-code-rules.ts", file)).exitCode).toBe(0);
});

test("rejects definite assignment, class functions, and never casts", async () => {
  const file = join(directory, "class.ts");
  const cases = [
    "let value!: string;",
    "class A { field!: string }",
    "class A { constructor() {} }",
    "class A { get x() { return 1; } }",
    "class A { set x(value: number) {} }",
    "const value = 1 as never as string;",
    "const value = <never>1;",
  ];
  for (const code of cases) {
    await writeFile(file, code);
    const result = await run("scripts/check-code-rules.ts", file);
    expect(result.exitCode, code).toBe(1);
  }
  await writeFile(
    file,
    "class E extends Error { override name = 'E'; }; declare class D { constructor(); get x(): number }",
  );
  expect((await run("scripts/check-code-rules.ts", file)).exitCode).toBe(0);
});

test("limits comments to one sentence", async () => {
  const file = join(directory, "comments.ts");
  await writeFile(file, "// First sentence. Second sentence.\nconst a = 1;");
  expect((await run("scripts/check-code-rules.ts", file)).exitCode).toBe(1);
  await writeFile(file, "const a = 1; /** One. Two. */");
  expect((await run("scripts/check-code-rules.ts", file)).exitCode).toBe(1);
  await writeFile(
    file,
    "// Uses v1.0.0, e.g. for tests; see `a.b`.\nconst a = 1; // Trailing note\n",
  );
  expect((await run("scripts/check-code-rules.ts", file)).exitCode).toBe(0);
});

test("exempts only files with the generated marker", async () => {
  const file = join(directory, "generated.ts");
  const code = "function generated(value: any) { return value! as unknown; }";
  await writeFile(file, code);
  expect((await run("scripts/check-code-rules.ts", file)).exitCode).toBe(1);
  await writeFile(file, `// @generated by @mcp-cli/codegen\n${code}`);
  expect((await run("scripts/check-code-rules.ts", file)).exitCode).toBe(0);
});
