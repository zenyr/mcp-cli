import { readdir } from "node:fs/promises";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const check = process.argv.includes("--check");
const NAME = /^[a-z][a-z0-9-]*$/;

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === "object" && value !== null && !Array.isArray(value);

const shim = (service?: string): string =>
  `#!/usr/bin/env bun\n// @generated by scripts/sync-bins.ts; do not edit.\nimport { run } from "../apps/cli/src/main";\n\nawait run(${service ? `[${JSON.stringify(service)}, ...process.argv.slice(2)]` : "process.argv.slice(2)"});\n`;

const serviceBins = async (): Promise<Array<{ bin: string; service: string }>> => {
  const found: Array<{ bin: string; service: string }> = [];
  for (const dir of (await readdir(join(root, "plugins"))).sort()) {
    const file = Bun.file(join(root, "plugins", dir, "package.json"));
    if (!(await file.exists())) continue;
    const pkg: unknown = await file.json();
    const marker = isRecord(pkg) ? pkg["mcp-cli"] : undefined;
    if (!isRecord(marker) || marker.bin === undefined) continue;
    const { bin, service } = marker;
    if (typeof bin !== "string" || !NAME.test(bin) || typeof service !== "string")
      throw new Error(`plugins/${dir}: mcp-cli.bin and mcp-cli.service must be valid names`);
    found.push({ bin, service });
  }
  return found;
};

const pkgFile = join(root, "package.json");
const pkg: unknown = await Bun.file(pkgFile).json();
if (!isRecord(pkg)) throw new Error("Invalid root package.json");
const bins = [{ bin: "mcp-cli", service: undefined }, ...(await serviceBins())];
// Sorted like oxfmt sorts package.json so the check and the formatter agree.
const desired: Record<string, string> = Object.fromEntries(
  [["mem", "apps/mem/src/main.ts"], ...bins.map(({ bin }) => [bin, `bin/${bin}.ts`])].sort(
    ([a = ""], [b = ""]) => a.localeCompare(b),
  ),
);

const problems: string[] = [];
if (JSON.stringify(pkg.bin) !== JSON.stringify(desired)) problems.push("package.json bin");
const expectedShims = new Set(bins.map(({ bin }) => `${bin}.ts`));
const existing = (await readdir(join(root, "bin")).catch(() => [])).filter((f) =>
  f.endsWith(".ts"),
);
for (const file of existing) if (!expectedShims.has(file)) problems.push(`bin/${file} (stale)`);
for (const { bin, service } of bins) {
  const path = join(root, "bin", `${bin}.ts`);
  const current = await Bun.file(path)
    .text()
    .catch(() => "");
  if (current !== shim(service)) problems.push(`bin/${bin}.ts`);
}

if (check) {
  if (problems.length) {
    console.error(`Service bins are out of date: ${problems.join(", ")}\nRun bun run bins`);
    process.exit(1);
  }
} else {
  pkg.bin = desired;
  await Bun.write(pkgFile, `${JSON.stringify(pkg, null, 2)}\n`);
  for (const file of existing)
    if (!expectedShims.has(file)) await Bun.file(join(root, "bin", file)).delete();
  for (const { bin, service } of bins) {
    const path = join(root, "bin", `${bin}.ts`);
    await Bun.write(path, shim(service));
    await Bun.$`chmod +x ${path}`;
  }
  console.log(`Synced bins: ${Object.keys(desired).join(", ")}`);
}
