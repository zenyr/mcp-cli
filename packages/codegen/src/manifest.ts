import { compile, type JSONSchema } from "json-schema-to-typescript";
import {
  applyCustomizations,
  canonicalize,
  isRecord,
  type GeneratedManifest,
  type ServicePlugin,
  type ToolDefinition,
} from "@mcp-cli/core";

import { pascalCase, uniqueName, withInputTypeNames } from "./naming";
import { isCompilerSchema, compilerSchema, validateSchema } from "./schema";

export const decodeTools = (value: unknown): ToolDefinition[] => {
  if (!Array.isArray(value)) throw new Error("Tools must be an array");
  return value.map((tool: unknown) => {
    if (
      !isRecord(tool) ||
      typeof tool.name !== "string" ||
      !tool.name.trim() ||
      !isRecord(tool.inputSchema) ||
      tool.inputSchema.type !== "object"
    ) {
      throw new Error("Tools require a name and an object input schema");
    }
    if (tool.description !== undefined && typeof tool.description !== "string")
      throw new Error("Invalid tool description");
    validateSchema(tool.inputSchema);
    if (tool.outputSchema !== undefined) {
      if (!isRecord(tool.outputSchema) || tool.outputSchema.type !== "object")
        throw new Error("Invalid tool output schema");
      validateSchema(tool.outputSchema);
    }
    return {
      name: tool.name,
      inputSchema: tool.inputSchema,
      ...(typeof tool.description === "string" && { description: tool.description }),
      ...(isRecord(tool.outputSchema) && { outputSchema: tool.outputSchema }),
    };
  });
};

export const byName = (a: ToolDefinition, b: ToolDefinition): number =>
  a.name < b.name ? -1 : a.name > b.name ? 1 : 0;

// Keeps only server-derived tools; plugin customizations are validated here and applied at run time.
export const createManifest = (plugin: ServicePlugin, tools: unknown): GeneratedManifest => {
  const decoded = decodeTools(tools).sort(byName);
  const manifest: GeneratedManifest = { version: 2, service: plugin.name, tools: decoded };
  applyCustomizations(plugin, manifest);
  return manifest;
};

export const generateModule = async (manifest: GeneratedManifest): Promise<string> => {
  const types: string[] = [];
  const used = new Set<string>();
  for (const [tool, name] of withInputTypeNames(manifest.tools, used)) {
    const schema = canonicalize(compilerSchema(tool.inputSchema));
    if (!isCompilerSchema(schema)) throw new Error("Invalid compiler schema");
    // Nested named types are prefixed with the root name to stay unique across tools.
    const customName = (nested: JSONSchema, key: string | undefined): string | undefined => {
      const base = nested.$id ?? key;
      if (base === undefined || base === name) return base;
      return uniqueName(`${name}${pascalCase(base)}`, used);
    };
    types.push(await compile(schema, name, { bannerComment: "", format: false, customName }));
  }
  return [
    "// @generated by mcp-cli codegen; do not edit.",
    'import type { GeneratedManifest } from "@mcp-cli/core";',
    `export const manifest = ${JSON.stringify(canonicalize(manifest), null, 2)} satisfies GeneratedManifest;`,
    ...types,
  ].join("\n");
};
