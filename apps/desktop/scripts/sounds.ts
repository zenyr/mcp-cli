import { soundDescriptions, soundKinds } from "../shared/ui-sounds";
import { soundRecipes } from "./sound-recipes";
import { synthesize } from "./sound-synthesis";

const entries: string[] = [];
for (const kind of soundKinds) {
  const wav = synthesize(soundRecipes[kind]);
  await Bun.write(
    new URL(`../assets/sounds/${soundDescriptions[kind].id}.wav`, import.meta.url),
    wav,
  );
  entries.push(`  ${kind}:\n    ${JSON.stringify(wav.toString("base64"))},`);
}
await Bun.write(
  new URL("../backend/sound-bank.ts", import.meta.url),
  `// @generated by scripts/sounds.ts\nexport const soundBank = {\n${entries.join("\n")}\n};\n`,
);
