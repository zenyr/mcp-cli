import { fileURLToPath } from "node:url";
import { Resvg } from "@resvg/resvg-js";

const render = async (source: string, target: string) => {
  const svg = await Bun.file(new URL(`../assets/${source}`, import.meta.url)).text();
  const png = new Resvg(svg, {
    fitTo: { mode: "width", value: 48 },
    font: { loadSystemFonts: false },
  })
    .render()
    .asPng();
  await Bun.write(new URL(`../assets/${target}`, import.meta.url), png);
  return png.toString("base64");
};
const template = await render("connection-mark.svg", "tray-template.png");
const color = await render("tray-color.svg", "tray-color.png");
const output = fileURLToPath(new URL("../backend/tray-images.ts", import.meta.url));
await Bun.write(
  output,
  `// @generated by scripts/tray-images.ts\nexport const trayImages = {\n  template:\n    ${JSON.stringify(template)},\n  color:\n    ${JSON.stringify(color)},\n};\n`,
);
