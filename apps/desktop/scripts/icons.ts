import { fileURLToPath } from "node:url";
import { renderIcon } from "./icon-render";

const source = await Bun.file(new URL("../assets/mcp-cli.svg", import.meta.url)).text();
const render = async (palette: "color" | "template", state: "running" | "stopped", width = 48) => {
  const icon = renderIcon(source, { palette, state, width });
  const filename = width === 1024 ? "mcp-cli.png" : `tray-${palette}-${state}.png`;
  await Bun.write(new URL(`../assets/${filename}`, import.meta.url), icon.png);
  return icon.png.toString("base64");
};
await render("color", "running", 1024);
const template = {
  running: await render("template", "running"),
  stopped: await render("template", "stopped"),
};
const color = {
  running: await render("color", "running"),
  stopped: await render("color", "stopped"),
};
const stateBlock = (images: { running: string; stopped: string }) => `{
    running:
      ${JSON.stringify(images.running)},
    stopped:
      ${JSON.stringify(images.stopped)},
  }`;
const output = fileURLToPath(new URL("../backend/tray-images.ts", import.meta.url));
await Bun.write(
  output,
  `// @generated by scripts/icons.ts
export const trayImages = {
  template: ${stateBlock(template)},
  color: ${stateBlock(color)},
};
`,
);
