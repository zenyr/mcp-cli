import { mkdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { UsageError } from "@mcp-cli/core";
import type { PackageManifest } from "./schema";

const server = `// @generated by mcp-cli plugins init
import { createInterface } from "node:readline";
const inputSchema = { type: "object", properties: { text: { type: "string" } }, required: ["text"] };
for await (const line of createInterface({ input: process.stdin })) {
  if (!line.trim()) continue;
  const request = JSON.parse(line);
  if (request.id === undefined) continue;
  let result;
  switch (request.method) {
    case "initialize":
      result = { protocolVersion: request.params.protocolVersion, capabilities: { tools: {} }, serverInfo: { name: "hello", version: "1.0.0" } };
      break;
    case "ping": result = {}; break;
    case "tools/list": result = { tools: [{ name: "echo", description: "Echo text", inputSchema }] }; break;
    case "tools/call":
      result = { content: [{ type: "text", text: String(request.params.arguments.text) }] };
      break;
    default:
      console.log(JSON.stringify({ jsonrpc: "2.0", id: request.id, error: { code: -32601, message: "Unknown method" } }));
      continue;
  }
  console.log(JSON.stringify({ jsonrpc: "2.0", id: request.id, result }));
}
`;

export const scaffold = async (service: string, directory: string): Promise<void> => {
  if (!/^[a-z][a-z0-9-]{0,63}$/.test(service))
    throw new UsageError("Use a lowercase service name.");
  const plugin: PackageManifest = {
    schemaVersion: 1,
    id: `local.${service}`,
    service,
    name: service,
    description: "Local MCP example",
    version: "1.0.0",
    permissions: { localCode: true, network: [], filesystem: [] },
    commands: { echo: { path: ["message", "echo"], summary: "Echo text" } },
    implementation: { type: "mcp", server: { type: "stdio", runtime: "bun", entry: "server.mjs" } },
  };
  await mkdir(directory);
  try {
    await writeFile(join(directory, "plugin.json"), `${JSON.stringify(plugin, null, 2)}\n`);
    await writeFile(
      join(directory, "manifest.json"),
      `${JSON.stringify(
        {
          version: 2,
          service,
          tools: [
            {
              name: "echo",
              description: "Echo text",
              inputSchema: {
                type: "object",
                properties: { text: { type: "string" } },
                required: ["text"],
              },
            },
          ],
        },
        null,
        2,
      )}\n`,
    );
    await writeFile(join(directory, "server.mjs"), server);
  } catch (error) {
    await rm(directory, { recursive: true, force: true });
    throw error;
  }
};
