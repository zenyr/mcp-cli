import { mkdir, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { packageWorkspacePlugins } from "./package-plugins";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const output = resolve(process.argv[2] || join(root, "apps/cli/dist/mcp-cli"));
const directory = await mkdtemp(join(tmpdir(), "mcp-cli-build-"));
try {
  await packageWorkspacePlugins(root, `${output}.plugins`);
  const entry = join(directory, "main.ts");
  await Bun.write(
    entry,
    [
      "// @generated by apps/cli/scripts/build.ts",
      `import { run } from ${JSON.stringify(join(root, "apps/cli/src/main.ts"))};`,
      `import { runPluginRuntime } from ${JSON.stringify(join(root, "apps/cli/src/marketplace/runtime.ts"))};`,
      'if (process.argv[2] === "--plugin-runtime") await runPluginRuntime(process.argv.slice(3));',
      "else await run(process.argv.slice(2));",
    ].join("\n"),
  );
  await mkdir(dirname(output), { recursive: true });
  const child = Bun.spawn(
    [
      process.execPath,
      "build",
      entry,
      "--compile",
      "--define",
      "MCP_CLI_BUNDLED=true",
      "--outfile",
      output,
    ],
    {
      cwd: root,
      stdout: "inherit",
      stderr: "inherit",
    },
  );
  if ((await child.exited) !== 0) throw new Error("CLI 빌드에 실패했습니다.");
} finally {
  await rm(directory, { recursive: true, force: true });
}
