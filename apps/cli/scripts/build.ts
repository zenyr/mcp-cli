import { mkdir, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { workspacePackages } from "../src/packages";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const output = resolve(process.argv[2] || join(root, "apps/cli/dist/mcp-cli"));
const directory = await mkdtemp(join(tmpdir(), "mcp-cli-build-"));
try {
  const plugins = await workspacePackages(root);
  const imports: string[] = [];
  const definitions: string[] = [];
  for (const [index, info] of plugins.entries()) {
    imports.push(`import plugin${index} from ${JSON.stringify(info.entry)};`);
    imports.push(
      `import { manifest as manifest${index} } from ${JSON.stringify(join(info.dir, "src/generated.ts"))};`,
    );
    definitions.push(
      `{ packageName: ${JSON.stringify(info.name)}, plugin: plugin${index}, manifest: manifest${index} }`,
    );
  }
  const entry = join(directory, "main.ts");
  await Bun.write(
    entry,
    [
      "// @generated by apps/cli/scripts/build.ts",
      `import { installBundledPlugins } from ${JSON.stringify(join(root, "apps/cli/src/bundled.ts"))};`,
      `import { run } from ${JSON.stringify(join(root, "apps/cli/src/main.ts"))};`,
      ...imports,
      `installBundledPlugins([${definitions.join(",\n")}]);`,
      `if (process.argv[2] === "--demo-server") await import(${JSON.stringify(join(root, "plugins/demo/src/server.ts"))});`,
      "else await run(process.argv.slice(2));",
    ].join("\n"),
  );
  await mkdir(dirname(output), { recursive: true });
  const child = Bun.spawn(
    [
      process.execPath,
      "build",
      entry,
      "--compile",
      "--define",
      "MCP_CLI_BUNDLED=true",
      "--outfile",
      output,
    ],
    {
      cwd: root,
      stdout: "inherit",
      stderr: "inherit",
    },
  );
  if ((await child.exited) !== 0) throw new Error("CLI 빌드에 실패했습니다.");
} finally {
  await rm(directory, { recursive: true, force: true });
}
